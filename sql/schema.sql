-- Создание таблиц
CREATE TABLE IF NOT EXISTS sellers (
    seller_id CHAR(64) PRIMARY KEY,
    seller_rating DECIMAL(10,2) NOT NULL,
    review_count INT NOT NULL
    );
    
CREATE TABLE IF NOT EXISTS goods (
    game_id BIGINT PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    description TEXT NOT NULL,
    brand VARCHAR(150),
    photo_count INTEGER NOT NULL,
    condition VARCHAR(30) NOT NULL,
    category VARCHAR(30) NOT NULL,
    likes_count INTEGER NOT NULL,
    listed_date DATE NOT NULL,
    price DECIMAL(8,2) NOT NULL,
    price_with_protection DECIMAL(8,2) NOT NULL,
    shipping_cost DECIMAL(8,2) NOT NULL,
    currency_code VARCHAR(10) NOT NULL,
    status VARCHAR(10) DEFAULT 'active',
    sold_date DATE,
    seller_id CHAR(64) REFERENCES sellers(seller_id) NOT NULL
    );

CREATE TABLE IF NOT EXISTS exchange_rates (
    currency_code VARCHAR(10) NOT NULL,
    date DATE NOT NULL,
    CONSTRAINT exchange_id PRIMARY KEY (currency_code, date),
    exchange_rate DECIMAL(8,2) NOT NULL
);

CREATE TABLE IF NOT EXISTS rating_changes (
	seller_id CHAR(64) REFERENCES sellers(seller_id) NOT NULL,
	date DATE NOT NULL,
	CONSTRAINT rating_change_id PRIMARY KEY (seller_id, date),
	seller_rating DECIMAL(10,2) NOT NULL,
    review_count INT NOT NULL
);

CREATE TABLE IF NOT EXISTS item_metrics_history (
    game_id BIGINT REFERENCES goods(game_id),
    date DATE NOT NULL,
    CONSTRAINT item_metrics_history_id PRIMARY KEY (game_id, date),
    price DECIMAL(8,2) NOT NULL,
    price_with_protection DECIMAL(8,2) NOT NULL,
    shipping_cost DECIMAL(8,2) NOT NULL,
    likes_count INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS game_id_snapshots (
    game_id BIGINT,
    snapshot_datetime TIMESTAMPTZ,
    CONSTRAINT game_id_snapshot_datetime PRIMARY KEY (game_id,snapshot_datetime)
);

CREATE TABLE IF NOT EXISTS run_log (
	log_id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	run_type VARCHAR(30) NOT NULL,
	start_time TIMESTAMPTZ NOT NULL,
	end_time TIMESTAMPTZ NOT NULL,
	processed_game_count INTEGER NOT NULL
); 